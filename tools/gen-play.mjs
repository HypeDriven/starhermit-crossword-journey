// Writes the play scripts tests/native.mjs runs (`npm run plays`): each
// drives the real UI by pointer and keys at the render check's 960 × 540
// (the compact layout: the current clue over the board, the drawers, the
// tray with the letters field) through a full page to its results, the
// solutions typed into the letters field as tools/plan.mjs solves them.
import { writeFileSync, mkdirSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';
import * as C from '../js/content.js';
import { plan } from './plan.mjs';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const out = join(root, 'tests', 'native');
mkdirSync(out, { recursive: true });

/** The plan as play-script lines: letters typed into the focused field, Enter / arrows as keys, assists by the tray. */
function solveLines(def, opts) {
  const lines = [];
  for (const s of plan(def, opts).steps) {
    if (s.type) lines.push(`type ${s.type}`, 'frames 3');
    else if (s.key) lines.push(`key ${s.key} 1`, 'frames 3');
    else if (s.action === 'check') lines.push('frames 5', 'click =Check', 'frames 10');
    else if (s.action === 'reveal') lines.push('frames 5', 'click =Reveal', 'frames 10');
  }
  return lines;
}
const header = (text) => text.split('\n').map((l) => `# ${l}`).join('\n');

